def generate_patient_spatial_viz(
    patient_id: str,
    attention_data: Dict,
    pathway_names: List[str],
    fold_analysis_dir: str,
    output_dir: str,
    risk_group: str,
    wsi_features_dir: Optional[str] = None,
    h5_dir: Optional[str] = None,
    wsi_dir: Optional[str] = None,
    wsi_path: Optional[str] = None,
    patch_size: int = 256,
    downsample: int = 4,
    slide_type_filter: str = 'DX',
    max_slides: int = 2,
    single_pathway_name: Optional[str] = None,
    single_pathway_idx: Optional[int] = None,
    rank_transform: bool = False,
):
    """
    Generate all spatial visualizations for a patient.

    Produces per-slide figures with:
        1. H&E tissue canvas
        2. Prototype assignment overlay
        3. Risk-aware pathway overlay (Option C)
        4. (Optional) Single-pathway attention heatmap

    Coordinate loading priority:
        1. wsi_features_dir — load from preprocessed .pt file (preferred,
           requires preprocess_wsi with coords patch)
        2. h5_dir — re-read original h5 files (fallback)

    Args:
        patient_id: TCGA patient ID.
        attention_data: Dict from attention_by_patient[patient_id].
        pathway_names: Full pathway name list.
        fold_analysis_dir: Per-fold analysis directory with rank CSVs.
        output_dir: Output directory for figures.
        risk_group: 'High Risk' or 'Low Risk'.
        wsi_features_dir: Directory with preprocessed .pt files (preferred).
        h5_dir: Directory with original h5 files (fallback).
        wsi_dir: Directory to search for WSI files (for tissue canvas).
        wsi_path: Explicit WSI path (single-slide only).
        patch_size: Patch size at extraction magnification.
        downsample: Downsample factor for rendering.
        slide_type_filter: H5 filename filter.
        max_slides: Max slides per patient.
        single_pathway_name: Name of pathway for single-pathway heatmap.
        single_pathway_idx: Index of pathway (alternative to name).
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # ── Load slide data (prefer .pt, fallback to h5) ─────────────────
    slides = None

    if wsi_features_dir:
        slides = load_patient_spatial_data_from_pt(
            patient_id, wsi_features_dir
        )

    if slides is None and h5_dir:
        logger.info(f"Falling back to h5 loading for {patient_id}")
        slides = load_patient_slide_data(
            patient_id, h5_dir, slide_type_filter, max_slides
        )

    if slides is None:
        raise ValueError(
            f"Cannot load spatial data for {patient_id}. "
            f"Provide wsi_features_dir (preprocessed .pt with coords) "
            f"or h5_dir (original h5 files)."
        )

    # ── Extract attention signals ────────────────────────────────────
    pa = attention_data.get('patch_assignments', {})
    hard_assignments = np.asarray(pa.get('hard_assignments', pa.get('assignments', [])))
    gate_weights = np.asarray(pa.get('gate_weights', []))
    cross_modal = np.asarray(attention_data.get('cross_modal_attention', []))
    fusion_gate = np.asarray(attention_data.get('fusion_gate_weights', gate_weights))

    total_model_patches = len(hard_assignments)
    total_slide_patches = sum(s['n_patches'] for s in slides)

    if total_model_patches != total_slide_patches:
        logger.warning(
            f"Patch count mismatch: model has {total_model_patches} patches, "
            f"slides have {total_slide_patches}. Check preprocessing config "
            f"(max_slides={max_slides}, slide_type_filter='{slide_type_filter}')"
        )

    # ── Resolve single pathway ───────────────────────────────────────
    if single_pathway_name and single_pathway_idx is None:
        try:
            single_pathway_idx = pathway_names.index(single_pathway_name)
        except ValueError:
            logger.warning(
                f"Pathway '{single_pathway_name}' not found in pathway_names"
            )
            single_pathway_name = None

    if single_pathway_idx is not None and single_pathway_name is None:
        single_pathway_name = pathway_names[single_pathway_idx]

    # ── Generate per-slide visualizations ────────────────────────────
    for slide in slides:
        slide_id = slide['slide_id']
        offset = slide['feature_offset']
        n = slide['n_patches']
        coords = slide['coords']

        logger.info(
            f"  Rendering slide {slide_id} "
            f"(patches {offset}:{offset+n}, coords range: "
            f"x=[{coords[:,0].min()},{coords[:,0].max()}], "
            f"y=[{coords[:,1].min()},{coords[:,1].max()}])"
        )

        # Slice this slide's attention data
        slide_assignments = hard_assignments[offset:offset+n]
        slide_cross_modal = cross_modal  # [K, P] — shared across slides
        slide_gate_weights = gate_weights  # [K] — shared

        # ── Detect coordinate spacing ────────────────────────────────
        cs = infer_coord_spacing(coords)
        logger.info(f"    Coord spacing: {cs} (patch_size={patch_size})")

        # ── Build canvas ─────────────────────────────────────────────
        slide_wsi_path = _find_wsi_for_slide(slide_id, wsi_dir, wsi_path)

        if slide_wsi_path:
            logger.info(f"    Building canvas from WSI: {slide_wsi_path}")
            canvas = build_canvas_from_wsi(
                slide_wsi_path, coords, patch_size,
                downsample=downsample, coord_spacing=cs,
            )
        else:
            logger.info(f"    No WSI found, using coordinate-based canvas")
            canvas = build_canvas_from_coords(
                coords, patch_size,
                downsample=downsample, coord_spacing=cs,
            )

        overlays = []

        # ── Overlay 1: Prototype assignments ─────────────────────────
        proto_overlay, proto_colors = render_prototype_overlay(
            coords, slide_assignments, slide_gate_weights,
            patch_size, downsample, coord_spacing=cs,
        )
        proto_legend = [
            (proto_colors[i], f'Proto {i}')
            for i in sorted(set(slide_assignments.astype(int)))
        ]
        overlays.append({
            'image': proto_overlay,
            'title': 'Prototype Assignments',
            'legend': proto_legend,
        })

        # ── Overlay 2: Risk-aware pathway ────────────────────────────
        if len(slide_cross_modal) > 0 and pathway_names:
            pw_overlay, proto_pw_map, pw_colors = render_pathway_overlay(
                coords, slide_assignments, slide_cross_modal,
                slide_gate_weights, pathway_names, risk_group,
                fold_analysis_dir, patch_size, downsample,
                coord_spacing=cs,
            )

            # Build legend from proto-pathway map
            # Show unique pathways with truncated names
            seen = set()
            pw_legend = []
            for proto_idx in sorted(proto_pw_map.keys()):
                pw = proto_pw_map[proto_idx]
                if pw not in seen:
                    seen.add(pw)
                    display = pw[:35] + '...' if len(pw) > 35 else pw
                    pw_legend.append((pw_colors[pw], display))

            overlays.append({
                'image': pw_overlay,
                'title': f'Pathway ({risk_group.split()[0]}-Risk Direction)',
                'legend': pw_legend,
            })

        # ── Overlay 3: Single-pathway heatmap ────────────────────────
        if single_pathway_idx is not None and len(slide_cross_modal) > 0:
            display_name = single_pathway_name[:40]

            # Raw attention version
            ihc_overlay, vmin, vmax = render_single_pathway_heatmap(
                coords, slide_assignments, slide_cross_modal,
                single_pathway_idx, patch_size, downsample,
                coord_spacing=cs, rank_transform=False,
            )
            overlays.append({
                'image': ihc_overlay,
                'title': f'{display_name}',
                'colorbar': {
                    'cmap': 'inferno',
                    'vmin': vmin,
                    'vmax': vmax,
                    'label': 'Attention',
                },
            })

            # Rank-transformed version (percentile)
            if rank_transform:
                rank_overlay, rvmin, rvmax = render_single_pathway_heatmap(
                    coords, slide_assignments, slide_cross_modal,
                    single_pathway_idx, patch_size, downsample,
                    coord_spacing=cs, rank_transform=True,
                )
                overlays.append({
                    'image': rank_overlay,
                    'title': f'{display_name} (rank)',
                    'colorbar': {
                        'cmap': 'inferno',
                        'vmin': rvmin,
                        'vmax': rvmax,
                        'label': 'Percentile',
                    },
                })

        # ── Extract and visualize prototype exemplar patches ─────
        try:
            exemplars = extract_exemplar_patches(
                patient_id=patient_id,
                attention_data=attention_data,
                coords=coords,
                canvas=canvas,
                downsample=downsample,
                coord_spacing=cs,
                top_k_protos=5,
                n_patches_per_proto=5,
                wsi_path=slide_wsi_path,
                patch_size=patch_size,
            )

            if exemplars:
                weights = np.asarray(
                    pa.get('gate_weights',
                           attention_data.get('fusion_gate_weights', []))
                )

                # Full exemplar grid for this slide
                plot_prototype_exemplars(
                    exemplars=exemplars,
                    importance_weights=weights,
                    output_dir=str(output_dir),
                    slide_id=slide_id,
                    proto_colors=proto_colors,
                    dpi=300,
                )

                # # Exemplar strip for prototype assignment overlay
                # visible_protos = sorted(set(slide_assignments.astype(int)))
                # plot_overlay_exemplar_strip(
                #     exemplars=exemplars,
                #     visible_protos=visible_protos,
                #     importance_weights=weights,
                #     overlay_title='Prototype Assignments',
                #     output_dir=str(output_dir),
                #     slide_id=slide_id,
                #     proto_colors=proto_colors,
                # )

        except Exception as e:
            logger.warning(f"Exemplar extraction failed for {slide_id}: {e}")

        # ── Compose and save ─────────────────────────────────────────
        output_path = output_dir / f'{patient_id}_spatial.pdf'
        plot_spatial_figure(
            canvas, overlays, str(output_path),
            patient_id, slide_id, risk_group,
        )

    logger.info(f"Spatial visualization complete for {patient_id}")


def _find_wsi_for_slide(
    slide_id: str,
    wsi_dir: Optional[str],
    wsi_path: Optional[str],
) -> Optional[str]:
    """
    Try to find a WSI file matching a slide ID.

    Args:
        slide_id: Slide identifier (e.g., 'TCGA-A6-2671-01Z-00-DX1').
        wsi_dir: Directory to search for WSI files.
        wsi_path: Explicit path (returned directly if provided).

    Returns:
        Path to WSI file, or None if not found.
    """
    if wsi_path and os.path.exists(wsi_path):
        return wsi_path

    if wsi_dir is None:
        return None

    wsi_dir = Path(wsi_dir)
    wsi_extensions = ['.svs', '.ndpi', '.tiff', '.tif', '.mrxs']

    for ext in wsi_extensions:
        candidate = wsi_dir / f'{slide_id}{ext}'
        if candidate.exists():
            return str(candidate)

    # Fuzzy match: slide_id might be a prefix
    for ext in wsi_extensions:
        matches = list(wsi_dir.glob(f'{slide_id}*{ext}'))
        if matches:
            return str(matches[0])

    return None


