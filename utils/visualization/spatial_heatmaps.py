# 1b. Loading from preprocessed .pt files (preferred)
# =====================================================================

def load_patient_spatial_data_from_pt(
    patient_id: str,
    wsi_features_dir: str,
) -> List[Dict]:
    """
    Load spatial data from the preprocessed .pt file directly.

    This is the preferred loading path when preprocess_wsi.py has been
    run with the coords patch applied. The .pt file contains features,
    coords, and slide boundary metadata — no h5 re-reading needed.

    Falls back gracefully if the .pt file uses the old format (bare
    tensor without coords).

    Args:
        patient_id: Patient ID.
        wsi_features_dir: Directory containing {patient_id}.pt files.

    Returns:
        List of slide dicts in concatenation order (same format as
        load_patient_slide_data), or None if coords unavailable.
    """
    import torch

    pt_path = os.path.join(wsi_features_dir, f"{patient_id}.pt")
    if not os.path.exists(pt_path):
        return None

    data = torch.load(pt_path, weights_only=False)

    # Old format: bare tensor — no coords available
    if isinstance(data, torch.Tensor):
        logger.warning(
            f"Old-format .pt file for {patient_id} (no coords). "
            f"Re-run preprocess_wsi to include coordinates."
        )
        return None

    # New format: dict with features, coords, slide_info
    coords = data.get('coords')
    slide_info = data.get('slide_info')

    if coords is None:
        logger.warning(f"No coords in .pt file for {patient_id}")
        return None

    coords_np = coords.numpy() if hasattr(coords, 'numpy') else np.asarray(coords)

    # If no slide_info, treat as single slide
    if slide_info is None:
        slide_info = [{
            'slide_id': patient_id,
            'h5_filename': f'{patient_id}.h5',
            'n_patches': coords_np.shape[0],
            'feature_offset': 0,
        }]

    # Build slide list with per-slide coord slicing
    slides = []
    for si in slide_info:
        offset = si['feature_offset']
        n = si['n_patches']
        slides.append({
            'h5_path': None,
            'slide_id': si['slide_id'],
            'coords': coords_np[offset:offset+n],
            'features': None,  # Not needed for visualization
            'n_patches': n,
            'feature_offset': offset,
        })

    total = sum(s['n_patches'] for s in slides)
    logger.info(
        f"Loaded spatial data from .pt for {patient_id}: "
        f"{len(slides)} slides, {total} patches"
    )

    return slides


