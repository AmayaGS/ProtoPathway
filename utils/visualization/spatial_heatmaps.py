def infer_coord_spacing(coords: np.ndarray) -> int:
    """
    Infer the patch footprint in coordinate space from the coord grid.

    UNI-2h extracts 256×256 patches at 20x, but h5 coords are at
    level 0 (often 40x), so adjacent patches are spaced 512 apart.
    This function detects that spacing automatically.

    Strategy: compute the smallest non-zero difference along each axis
    across all patch pairs. The mode of these differences is the grid
    step.

    Args:
        coords: [N, 2] array of (x, y) top-left coordinates.

    Returns:
        Estimated patch footprint in coordinate space (e.g., 512).
    """
    if len(coords) < 2:
        return 256  # fallback

    # Get unique sorted values per axis
    unique_x = np.unique(coords[:, 0])
    unique_y = np.unique(coords[:, 1])

    # Compute minimum positive differences
    diffs = []
    if len(unique_x) > 1:
        dx = np.diff(unique_x)
        diffs.extend(dx[dx > 0].tolist())
    if len(unique_y) > 1:
        dy = np.diff(unique_y)
        diffs.extend(dy[dy > 0].tolist())

    if not diffs:
        return 256  # fallback

    # Mode of differences = grid spacing
    from collections import Counter
    spacing = Counter(diffs).most_common(1)[0][0]

    return int(spacing)


def _build_distinct_colormap(n: int) -> Dict[int, Tuple]:
    """
    Build a palette of n maximally distinct RGB colors.

    First 20 are hand-picked for perceptual separation (no pastel
    variants of the same hue). Beyond 20, additional colors are
    generated by evenly sampling HSV hue at high saturation.

    Args:
        n: Number of distinct colors needed.

    Returns:
        Dict mapping index -> (R, G, B) as uint8 tuples.
    """
    # 20 hand-picked colours: high saturation, spread across hue space,
    # avoiding adjacent-similar pairs that plague tab20
    _BASE = [
        (230,  25,  75),  # red
        ( 60, 180,  75),  # green
        (  0, 130, 200),  # blue
        (255, 225,  25),  # yellow
        (245, 130,  48),  # orange
        (145,  30, 180),  # purple
        ( 70, 240, 240),  # cyan
        (240,  50, 230),  # magenta
        (210, 245,  60),  # lime
        (250, 190, 212),  # pink
        (  0, 128, 128),  # teal
        (220, 190, 255),  # lavender
        (170, 110,  40),  # brown
        (255, 250, 200),  # beige
        (128,   0,   0),  # maroon
        (170, 255, 195),  # mint
        (128, 128,   0),  # olive
        (255, 215, 180),  # apricot
        (  0,   0, 128),  # navy
        (128, 128, 128),  # grey
    ]

    if n <= len(_BASE):
        return {i: _BASE[i] for i in range(n)}

    # Beyond 20: fill with HSV samples at S=0.9, V=0.9
    import colorsys
    palette = {i: _BASE[i] for i in range(len(_BASE))}
    extra_needed = n - len(_BASE)
    for j in range(extra_needed):
        hue = j / extra_needed
        r, g, b = colorsys.hsv_to_rgb(hue, 0.9, 0.9)
        palette[len(_BASE) + j] = (int(r * 255), int(g * 255), int(b * 255))

    return palette


