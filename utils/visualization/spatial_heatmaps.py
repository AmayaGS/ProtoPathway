def find_patient_h5_files(
    patient_id: str,
    h5_dir: str,
    slide_type_filter: str = 'DX',
    max_slides: int = 2,
) -> List[Path]:
    """
    Find h5 feature files for a patient, mimicking preprocess_wsi.py logic.

    Returns files in sorted order, truncated to the largest `max_slides`
    by patch count — matching the preprocessing concatenation order.

    Args:
        patient_id: TCGA patient ID (e.g., 'TCGA-A6-2671').
        h5_dir: Directory containing h5 files.
        slide_type_filter: Slide type substring filter (e.g., 'DX').
        max_slides: Maximum slides per patient (must match preprocessing).

    Returns:
        List of h5 file paths in concatenation order.
    """
    h5_dir = Path(h5_dir)
    candidates = []

    for ext in ['.h5', '.hdf5']:
        for f in h5_dir.glob(f'*{ext}'):
            # Check patient ID is in filename
            if patient_id not in f.name:
                continue
            # Apply slide type filter
            if slide_type_filter and slide_type_filter not in f.name:
                continue
            candidates.append(f)

    if not candidates:
        raise FileNotFoundError(
            f"No h5 files found for patient {patient_id} in {h5_dir}"
        )

    # Sort by patch count descending (matching preprocess_wsi.py truncation)
    candidates_with_size = []
    for f in candidates:
        with h5py.File(f, 'r') as h5:
            n_patches = _get_h5_feature_count(h5)
        candidates_with_size.append((f, n_patches))

    candidates_with_size.sort(key=lambda x: x[1], reverse=True)
    selected = [f for f, _ in candidates_with_size[:max_slides]]

    # Return in sorted order for reproducibility
    selected.sort(key=lambda x: x.name)

    logger.info(
        f"Found {len(candidates)} h5 files for {patient_id}, "
        f"using {len(selected)} (max_slides={max_slides})"
    )

    return selected


def load_h5_coords_and_features(h5_path: str) -> Tuple[np.ndarray, np.ndarray]:
    """
    Load patch coordinates and features from an h5 file.

    Args:
        h5_path: Path to h5 file.

    Returns:
        coords: [N, 2] array of (x, y) top-left patch coordinates.
        features: [N, D] array of patch features.
    """
    with h5py.File(h5_path, 'r') as f:
        # Load coordinates
        if 'coords' in f:
            coords = f['coords'][:]
        else:
            raise KeyError(
                f"No 'coords' key found in {h5_path}. "
                f"Available keys: {list(f.keys())}"
            )

        # Load features
        if 'features' in f:
            features = f['features'][:]
        elif 'feats' in f:
            features = f['feats'][:]
        else:
            key = list(f.keys())[0]
            features = f[key][:]

        features = features.squeeze()
        if features.ndim == 1:
            features = features.reshape(1, -1)

    return coords, features


def load_patient_slide_data(
    patient_id: str,
    h5_dir: str,
    slide_type_filter: str = 'DX',
    max_slides: int = 2,
) -> List[Dict]:
    """
    Load all slide data for a patient, preserving per-slide boundaries.

    This is the critical function that bridges the gap between the
    preprocessed (concatenated) features and the spatial coordinates.
    The returned slide list preserves the concatenation order so that
    feature index i in the model output maps to the correct slide and
    patch.

    Args:
        patient_id: TCGA patient ID.
        h5_dir: Directory with h5 files.
        slide_type_filter: Slide type filter.
        max_slides: Max slides (must match preprocessing).

    Returns:
        List of dicts, one per slide, in concatenation order:
            {
                'h5_path': Path,
                'slide_id': str,
                'coords': ndarray [N_slide, 2],
                'features': ndarray [N_slide, D],
                'n_patches': int,
                'feature_offset': int,  # start index in concatenated features
            }
    """
    h5_files = find_patient_h5_files(
        patient_id, h5_dir, slide_type_filter, max_slides
    )

    slides = []
    offset = 0

    for h5_path in h5_files:
        coords, features = load_h5_coords_and_features(str(h5_path))

        slide_id = h5_path.stem  # e.g., 'TCGA-A6-2671-01Z-00-DX1'

        slides.append({
            'h5_path': h5_path,
            'slide_id': slide_id,
            'coords': coords,
            'features': features,
            'n_patches': coords.shape[0],
            'feature_offset': offset,
        })

        offset += coords.shape[0]

    total_patches = sum(s['n_patches'] for s in slides)
    logger.info(
        f"Loaded {len(slides)} slides for {patient_id}: "
        f"{total_patches} total patches "
        f"(offsets: {[s['feature_offset'] for s in slides]})"
    )

    return slides


def _get_h5_feature_count(h5_file) -> int:
    """Get number of features/patches from an open h5 file."""
    if 'features' in h5_file:
        return h5_file['features'].shape[0]
    elif 'feats' in h5_file:
        return h5_file['feats'].shape[0]
    else:
        key = list(h5_file.keys())[0]
        return h5_file[key].shape[0]


