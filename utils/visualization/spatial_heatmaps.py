def build_canvas_from_wsi(
    wsi_path: str,
    coords: np.ndarray,
    patch_size: int = 256,
    level: int = 0,
    downsample: int = 1,
    coord_spacing: Optional[int] = None,
) -> np.ndarray:
    """
    Build tissue canvas by reading patch regions from a WSI file.

    Args:
        wsi_path: Path to WSI file (.svs, .ndpi, .tiff, etc.).
        coords: [N, 2] array of (x, y) top-left coordinates at level 0.
        patch_size: Patch size at extraction level (typically 256 for UNI-2h).
        level: OpenSlide level to read from (0 = highest resolution).
        downsample: Additional downsampling factor for the canvas.
        coord_spacing: Patch footprint in coordinate space. Auto-detected
            from coords if None. For UNI-2h with 40x level-0, this is
            typically 512 (256 pixels at 20x = 512 at 40x).

    Returns:
        canvas: RGB image array [H, W, 3].
    """
    if not HAS_OPENSLIDE:
        raise ImportError(
            "OpenSlide is required for WSI reading. "
            "Install with: pip install openslide-python"
        )

    if coord_spacing is None:
        coord_spacing = infer_coord_spacing(coords)
        logger.info(f"    Auto-detected coord spacing: {coord_spacing}")

    wsi = openslide.OpenSlide(wsi_path)

    # Read full patch footprint at level 0, then resize to target
    # coord_spacing is the footprint at level 0 (e.g., 512)
    read_size = coord_spacing
    effective_patch = int(coord_spacing / downsample)

    # Canvas dimensions
    max_x = int(coords[:, 0].max() / downsample) + effective_patch
    max_y = int(coords[:, 1].max() / downsample) + effective_patch

    canvas = np.full((max_y, max_x, 3), 240, dtype=np.uint8)

    from PIL import Image as PILImage

    for x, y in coords:
        region = wsi.read_region(
            (int(x), int(y)), level, (read_size, read_size)
        )
        patch_rgb = np.array(region.convert('RGB'))

        # Resize to effective canvas size
        if patch_rgb.shape[0] != effective_patch or patch_rgb.shape[1] != effective_patch:
            patch_pil = PILImage.fromarray(patch_rgb)
            patch_pil = patch_pil.resize(
                (effective_patch, effective_patch), PILImage.LANCZOS
            )
            patch_rgb = np.array(patch_pil)

        # Place on canvas
        cx = int(x / downsample)
        cy = int(y / downsample)
        ph, pw = patch_rgb.shape[:2]
        ph = min(ph, max_y - cy)
        pw = min(pw, max_x - cx)
        canvas[cy:cy+ph, cx:cx+pw] = patch_rgb[:ph, :pw]

    wsi.close()

    return canvas


def build_canvas_from_coords(
    coords: np.ndarray,
    patch_size: int = 256,
    downsample: int = 1,
    bg_color: int = 240,
    coord_spacing: Optional[int] = None,
) -> np.ndarray:
    """
    Build a blank canvas using coordinate layout only (no WSI needed).

    Useful for generating overlays when WSI files are not available.
    Patches appear as white rectangles on a grey background.

    Args:
        coords: [N, 2] array of (x, y) top-left coordinates.
        patch_size: Patch size at extraction level.
        downsample: Downsample factor.
        bg_color: Background grey value.
        coord_spacing: Patch footprint in coordinate space.
            Auto-detected from coords if None.

    Returns:
        canvas: RGB image array [H, W, 3].
    """
    if coord_spacing is None:
        coord_spacing = infer_coord_spacing(coords)

    effective_patch = int(coord_spacing / downsample)

    max_x = int(coords[:, 0].max() / downsample) + effective_patch
    max_y = int(coords[:, 1].max() / downsample) + effective_patch

    canvas = np.full((max_y, max_x, 3), bg_color, dtype=np.uint8)

    # Mark patch locations as white
    for x, y in coords:
        cx = int(x / downsample)
        cy = int(y / downsample)
        canvas[cy:cy+effective_patch, cx:cx+effective_patch] = 255

    return canvas


