def generate_batch_spatial_viz(
    patient_ids: List[str],
    attention_by_patient: Dict[str, Dict],
    predictions: 'pd.DataFrame',
    pathway_names: List[str],
    fold_analysis_dir: str,
    output_dir: str,
    wsi_features_dir: Optional[str] = None,
    h5_dir: Optional[str] = None,
    wsi_dir: Optional[str] = None,
    patch_size: int = 256,
    downsample: int = 4,
    single_pathway_name: Optional[str] = None,
    **kwargs,
):
    """
    Generate spatial visualizations for a batch of patients.

    Convenience wrapper for generate_patient_spatial_viz that
    automatically looks up risk group from predictions.

    Args:
        patient_ids: List of patient IDs to visualize.
        attention_by_patient: Full attention dict.
        predictions: DataFrame with patient_id and risk_group columns.
        pathway_names: Pathway names.
        fold_analysis_dir: Per-fold analysis directory.
        output_dir: Output directory.
        wsi_features_dir: Preprocessed .pt directory (preferred).
        h5_dir: Original h5 directory (fallback).
        wsi_dir: Optional WSI directory.
        patch_size: Patch size.
        downsample: Downsample factor.
        single_pathway_name: Optional pathway for IHC overlay.
        **kwargs: Additional kwargs for generate_patient_spatial_viz.
    """
    risk_map = dict(
        zip(predictions['patient_id'], predictions['risk_group'])
    )

    for pid in patient_ids:
        if pid not in attention_by_patient:
            logger.warning(f"No attention data for {pid}, skipping")
            continue

