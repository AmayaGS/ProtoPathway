def render_prototype_overlay(
    coords: np.ndarray,
    assignments: np.ndarray,
    gate_weights: np.ndarray,
    patch_size: int = 256,
    downsample: int = 1,
    n_prototypes: Optional[int] = None,
    coord_spacing: Optional[int] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Create RGBA overlay coloring each patch by prototype assignment.

    Uses uniform full opacity so prototype regions are clearly visible.
    Gate weight modulation is intentionally omitted because near-uniform
    weights (attention collapse) would make all patches equally faint.

    Args:
        coords: [N, 2] patch coordinates.
        assignments: [N] hard prototype assignment per patch.
        gate_weights: [K] prototype gate weights (reserved for future use).
        patch_size: Patch size at extraction level.
        downsample: Downsample factor.
        n_prototypes: Total number of prototypes (for colormap).
        coord_spacing: Patch footprint in coordinate space.

    Returns:
        overlay: RGBA image [H, W, 4] with prototype colors.
        cmap_dict: Dict mapping prototype_idx -> (R, G, B) tuple.
    """
    if coord_spacing is None:
        coord_spacing = infer_coord_spacing(coords)

    effective_patch = int(coord_spacing / downsample)
    max_x = int(coords[:, 0].max() / downsample) + effective_patch
    max_y = int(coords[:, 1].max() / downsample) + effective_patch

    if n_prototypes is None:
        n_prototypes = int(assignments.max()) + 1

    cmap_dict = _build_distinct_colormap(n_prototypes)

    overlay = np.zeros((max_y, max_x, 4), dtype=np.uint8)

    for i, (x, y) in enumerate(coords):
        proto_id = int(assignments[i])
        cx = int(x / downsample)
        cy = int(y / downsample)

        r, g, b = cmap_dict[proto_id]
        overlay[cy:cy+effective_patch, cx:cx+effective_patch] = [r, g, b, 255]

    return overlay, cmap_dict


def render_pathway_overlay(
    coords: np.ndarray,
    assignments: np.ndarray,
    cross_modal_attention: np.ndarray,
    gate_weights: np.ndarray,
    pathway_names: List[str],
    risk_group: str,
    fold_analysis_dir: str,
    patch_size: int = 256,
    downsample: int = 1,
    coord_spacing: Optional[int] = None,
) -> Tuple[np.ndarray, Dict[int, str], Dict[str, Tuple]]:
    """
    Risk-aware pathway overlay (Option C).

    For each prototype, selects the top pathway from the appropriate
    risk direction using per-fold rank analysis results.

    Args:
        coords: [N, 2] patch coordinates.
        assignments: [N] hard prototype assignment per patch.
        cross_modal_attention: [K, P] cross-modal attention matrix.
        gate_weights: [K] prototype gate weights (reserved for future use).
        pathway_names: Full pathway name list.
        risk_group: Patient's risk group ('High Risk' or 'Low Risk').
        fold_analysis_dir: Path to per-fold analysis CSVs.
        patch_size: Patch size.
        downsample: Downsample factor.
        coord_spacing: Patch footprint in coordinate space.

    Returns:
        overlay: RGBA image [H, W, 4].
        proto_pathway_map: Dict[proto_idx -> pathway_name].
        pathway_colors: Dict[pathway_name -> (R, G, B)].
    """
    if coord_spacing is None:
        coord_spacing = infer_coord_spacing(coords)

    n_prototypes = cross_modal_attention.shape[0]

    # Load per-prototype rank analysis and select top pathway per direction
    proto_pathway_map = _select_risk_aware_pathways(
        fold_analysis_dir, n_prototypes, risk_group
    )

    # Assign distinct colors to the unique pathways
    unique_pathways = sorted(set(proto_pathway_map.values()))
    pw_color_map = _build_distinct_colormap(len(unique_pathways))
    pathway_colors = {
        pw: pw_color_map[i]
        for i, pw in enumerate(unique_pathways)
    }

    effective_patch = int(coord_spacing / downsample)
    max_x = int(coords[:, 0].max() / downsample) + effective_patch
    max_y = int(coords[:, 1].max() / downsample) + effective_patch

    overlay = np.zeros((max_y, max_x, 4), dtype=np.uint8)

    for i, (x, y) in enumerate(coords):
        proto_id = int(assignments[i])
        cx = int(x / downsample)
        cy = int(y / downsample)

        pathway = proto_pathway_map.get(proto_id)
        if pathway is None:
            continue

        r, g, b = pathway_colors[pathway]
        overlay[cy:cy+effective_patch, cx:cx+effective_patch] = [r, g, b, 255]

    return overlay, proto_pathway_map, pathway_colors


def render_single_pathway_heatmap(
    coords: np.ndarray,
    assignments: np.ndarray,
    cross_modal_attention: np.ndarray,
    pathway_idx: int,
    patch_size: int = 256,
    downsample: int = 1,
    cmap_name: str = 'inferno',
    coord_spacing: Optional[int] = None,
    rank_transform: bool = False,
) -> Tuple[np.ndarray, float, float]:
    """
    Continuous heatmap for a single pathway — computational IHC stain.

    Each patch is colored by how strongly its prototype attends to the
    specified pathway.

    Args:
        coords: [N, 2] patch coordinates.
        assignments: [N] hard prototype assignment per patch.
        cross_modal_attention: [K, P] cross-modal attention.
        pathway_idx: Index of the target pathway.
        patch_size: Patch size.
        downsample: Downsample factor.
        cmap_name: Matplotlib colormap name.
        coord_spacing: Patch footprint in coordinate space.
        rank_transform: If True, map values to percentile ranks
            before coloring. Spreads the full colormap across the
            data regardless of the raw value distribution — useful
            when attention magnitudes are near-uniform.

    Returns:
        overlay: RGBA image [H, W, 4].
        vmin: Minimum value used for colorbar (raw or percentile).
        vmax: Maximum value used for colorbar (raw or percentile).
    """
    if coord_spacing is None:
        coord_spacing = infer_coord_spacing(coords)

    effective_patch = int(coord_spacing / downsample)
    max_x = int(coords[:, 0].max() / downsample) + effective_patch
    max_y = int(coords[:, 1].max() / downsample) + effective_patch

    # Per-prototype attention to this pathway
    proto_pw_attn = cross_modal_attention[:, pathway_idx]  # [K]

    # Per-patch attention (via assignment)
    patch_attn = proto_pw_attn[assignments.astype(int)]  # [N]

    if rank_transform:
        from scipy.stats import rankdata
        # Average rank, scaled to [0, 1] percentile
        patch_values = (rankdata(patch_attn) - 1) / max(len(patch_attn) - 1, 1)
        vmin, vmax = 0.0, 1.0
    else:
        patch_values = patch_attn
        vmin, vmax = float(patch_attn.min()), float(patch_attn.max())

    norm = Normalize(vmin=vmin, vmax=vmax)
    cmap = plt.cm.get_cmap(cmap_name)

    overlay = np.zeros((max_y, max_x, 4), dtype=np.uint8)

    for i, (x, y) in enumerate(coords):
        cx = int(x / downsample)
        cy = int(y / downsample)

        rgba = cmap(norm(patch_values[i]))
        overlay[cy:cy+effective_patch, cx:cx+effective_patch] = [
            int(rgba[0] * 255),
            int(rgba[1] * 255),
            int(rgba[2] * 255),
            255,
        ]

    return overlay, vmin, vmax


