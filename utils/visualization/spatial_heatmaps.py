def _select_risk_aware_pathways(
    analysis_dir: str,
    n_prototypes: int,
    risk_group: str,
) -> Dict[int, str]:
    """
    Select the top risk-direction-relevant pathway for each prototype
    from per-fold rank analysis results.

    For high-risk patients: select pathway with largest positive
    rank_difference (higher importance in high-risk group).
    For low-risk patients: select pathway with largest negative
    rank_difference (higher importance in low-risk group).

    Args:
        analysis_dir: Directory containing crossmodal_proto_*_rank_analysis.csv.
        n_prototypes: Number of prototypes.
        risk_group: 'High Risk' or 'Low Risk'.

    Returns:
        Dict[proto_idx -> pathway_name].
    """
    analysis_dir = Path(analysis_dir)
    proto_pathway_map = {}

    for proto_idx in range(n_prototypes):
        csv_path = analysis_dir / f'crossmodal_proto_{proto_idx}_rank_analysis.csv'

        if not csv_path.exists():
            logger.warning(f"Missing rank analysis for prototype {proto_idx}")
            continue

        df = pd.read_csv(csv_path)

        if 'High' in risk_group:
            # Top pathway with positive rank_difference (high-risk associated)
            candidates = df[df['rank_difference'] > 0]
            if len(candidates) == 0:
                candidates = df  # fallback to overall top
            top = candidates.nlargest(1, 'rank_difference')
        else:
            # Top pathway with negative rank_difference (low-risk associated)
            candidates = df[df['rank_difference'] < 0]
            if len(candidates) == 0:
                candidates = df
            top = candidates.nsmallest(1, 'rank_difference')

        if len(top) > 0:
            proto_pathway_map[proto_idx] = top.iloc[0]['entity']

    logger.info(
        f"Selected risk-aware pathways for {len(proto_pathway_map)} prototypes "
        f"(direction: {risk_group})"
    )

    return proto_pathway_map


